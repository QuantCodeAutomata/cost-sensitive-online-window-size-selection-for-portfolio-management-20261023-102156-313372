"""
Synthetic data generator for the regime-shift portfolio experiments (Section 4.1).

Paper: Cost-Sensitive Online Window Size Selection for Portfolio Management
Authors: Yi-Chen Liu, Chung-Han Hsieh (arXiv:2609.29887v2)
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from src.config import (
    SYN_N_STOCKS,
    SYN_T,
    SYN_REGIME_CHANGE,
    SYN_J1,
    SYN_J2,
    SYN_START_DATE,
    SYN_MU_DAILY,
    SYN_ALPHA,
    SYN_SIGMA,
    SYN_SEED,
    WINDOWS_SMALL,
)


def generate_synthetic_returns(
    n_stocks: int = SYN_N_STOCKS,
    T: int = SYN_T,
    regime_change: int = SYN_REGIME_CHANGE,
    j1: int = SYN_J1,
    j2: int = SYN_J2,
    mu_daily: float = SYN_MU_DAILY,
    alpha: float = SYN_ALPHA,
    sigma: float = SYN_SIGMA,
    seed: int = SYN_SEED,
    start_date: str = SYN_START_DATE,
    extra_presample: int | None = None,
    windows: list[int] | None = None,
) -> tuple[pd.DataFrame, pd.DatetimeIndex]:
    """
    Generate synthetic daily returns using the autoregressive moving-window model
    from Section 4.1 (data generating process, Eq. in Section 4.1).

    y(t) = mu + alpha * ((1/j_t) * sum_{k=1}^{j_t} y(t-k) - mu) + epsilon(t)

    where epsilon(t) ~ N(0, sigma^2 * I) i.i.d., and
        j_t = j1 for t = 1, ..., regime_change
        j_t = j2 for t = regime_change+1, ..., T

    At least max(j1, j2) presample observations are generated by drawing from N(mu, sigma^2*I).

    Parameters
    ----------
    n_stocks : int
        Number of synthetic assets (paper: 32).
    T : int
        Number of evaluation periods (paper: 2000).
    regime_change : int
        First period using j2 (1-indexed); paper: 1001 (first 1000 use j1).
    j1, j2 : int
        Window sizes governing the two regimes.
    mu_daily : float
        Baseline daily expected return per stock (assumed; paper: unspecified).
    alpha : float
        Signal coefficient in (0, 1) (assumed; paper: unspecified).
    sigma : float
        Gaussian noise std (assumed; paper: unspecified, notation N(0, sigma^2)).
    seed : int
        Random seed (assumed).
    start_date : str
        First business date of the evaluation period.
    extra_presample : int or None
        Additional presample rows to generate. If None, defaults to max(windows) or max(j1,j2).
    windows : list[int] or None
        Candidate window sizes; used to determine presample length.

    Returns
    -------
    returns_with_presample : pd.DataFrame, shape (n_presample + T, n_stocks)
        Rows 0..n_presample-1 are presample; rows n_presample.. are evaluation.
        Columns are labeled SYN_1, ..., SYN_{n_stocks}.
    eval_dates : pd.DatetimeIndex, length T
        Business-day dates for the evaluation period.
    """
    rng = np.random.default_rng(seed)
    mu = np.full(n_stocks, mu_daily)

    if windows is None:
        windows = WINDOWS_SMALL
    n_presample = extra_presample if extra_presample is not None else max(windows)
    assert n_presample >= max(j1, j2), (
        f"n_presample={n_presample} must be >= max(j1={j1}, j2={j2})"
    )

    total_len = n_presample + T
    all_returns = np.zeros((total_len, n_stocks))

    # Initialize presample from N(mu, sigma^2 * I)
    all_returns[:n_presample] = rng.normal(
        loc=mu, scale=sigma, size=(n_presample, n_stocks)
    )

    # Build j_t schedule (1-indexed for evaluation; 0-indexed offset = n_presample)
    j_schedule = np.full(T, j2, dtype=int)
    j_schedule[:regime_change] = j1  # first `regime_change` periods use j1

    # Recursive simulation (Section 4.1)
    for t_eval in range(T):
        t_abs = n_presample + t_eval  # absolute index into all_returns
        j_t = int(j_schedule[t_eval])

        # Rolling mean of the last j_t returns PRIOR to time t (look-back only)
        past_slice = all_returns[t_abs - j_t : t_abs]  # shape (j_t, n_stocks)
        rolling_mean = past_slice.mean(axis=0)

        eps = rng.normal(scale=sigma, size=n_stocks)
        all_returns[t_abs] = mu + alpha * (rolling_mean - mu) + eps

    # Build date index for evaluation period (business days)
    eval_dates = pd.bdate_range(start=start_date, periods=T)

    columns = [f"SYN_{i + 1}" for i in range(n_stocks)]
    full_index = pd.RangeIndex(total_len)
    df = pd.DataFrame(all_returns, columns=columns, index=full_index)

    return df, eval_dates


def get_regime_change_date(
    start_date: str,
    regime_change: int,
) -> pd.Timestamp:
    """Return the business-day date of the regime change (first day of second regime)."""
    dates = pd.bdate_range(start=start_date, periods=regime_change + 1)
    return dates[regime_change]
